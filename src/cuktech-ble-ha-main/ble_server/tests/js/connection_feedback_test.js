'use strict';
const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const root = path.resolve(__dirname, '../../web/static');
const sandbox = { console, URL, Map, Promise, setTimeout, clearTimeout, AbortController, location: {href:'http://localhost/', origin:'http://localhost'}, localStorage:{getItem(){},setItem(){}}, I18N:{t:k=>k} };
sandbox.window = sandbox;
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(root,'device-store.js'),'utf8'), sandbox);
sandbox.DeviceStore.init({defaults:()=>({})});
const desktopMarkup = fs.readFileSync(path.join(root,'../index.html'),'utf8');
assert.ok(desktopMarkup.includes('</div>\n        <div class="wrap connection-feedback-row">\n            <div id="connectionFeedback"'), 'desktop feedback occupies its own row after the topbar flex controls');
const source = path.join(root,'connection-feedback.js');
assert.ok(fs.existsSync(source), 'shared connection feedback module exists');
vm.runInContext(fs.readFileSync(source,'utf8'), sandbox);
const F = sandbox.ConnectionFeedback, S = sandbox.DeviceStore;
const error = {code:'device_not_found',stage:'scanning',occurred_at:1};
for (const code of ['bluetooth_off','permission_denied','adapter_unavailable','bluetooth_busy','device_not_found','connection_timeout','authentication_failed','connection_lost','connection_failed']) {
 assert.ok(F.describe({connection:{phase:'retry_wait',last_error:{code}}}).text.includes('connectionFeedback.'+code));
}
assert.ok(F.describe({connection:{phase:'retry_wait',last_error:{code:'unknown'}}}).text.includes('connectionFeedback.connection_failed'));
const container={textContent:'',setAttribute(k,v){this[k]=v;}};
F.render(container,{phase:'retry_wait',last_error:error},true);
assert.equal(container['aria-live'],'polite');
assert.ok(container.textContent.includes('serviceUnavailable'));
assert.ok(container.textContent.includes('device_not_found'));
F.render(container,{phase:'connected',last_error:null},false);
assert.equal(container.hidden,true);
S.dispatch({type:'status', connection:{phase:'retry_wait',last_error:error},connected:false,authenticated:false});
assert.equal(S.get('default').connection.last_error.code,'device_not_found');
assert.ok(F.describe(S.get('default')).text.includes('connectionFeedback.device_not_found'));
S.dispatch({type:'status',connection:{phase:'scanning',last_error:error}});
assert.equal(F.describe(S.get('default')).action,'stop');
assert.ok(F.describe(S.get('default')).text.includes('connectionFeedback.device_not_found'));
assert.equal(F.describe({connected:true,authenticated:true}).action,'stop');
assert.equal(F.describe({}).action,'connect');
S.dispatch({type:'status',connection:{phase:'connected',last_error:error},connected:true,authenticated:true});
assert.equal(S.get('default').connection.last_error,null);
S.dispatch({type:'status',connection:{phase:'disabled',last_error:error}});
assert.equal(S.get('default').connection.last_error,null);
(async()=>{
 let release, calls=[];
 sandbox.fetch=(url,opts)=>{calls.push({url,body:JSON.parse(opts.body)});return new Promise(r=>release=r);};
 S.get('default').connection={phase:'retry_wait',last_error:error};
 const request=F.request('retry');
 await F.request('retry');
 assert.equal(calls.length,1);
 assert.deepEqual(calls[0].body,{enabled:true,retry:true});
 assert.equal(S.get('default').connection.last_error.code,'device_not_found');
 S.switchDevice('other');
 release({ok:false,json:async()=>({ok:false})}); await request;
 assert.equal(S.get('other').communicationError,undefined);
 assert.equal(S.get('default').communicationError,true);
 sandbox.fetch=async(url,opts)=>{if(opts && opts.body) calls.push({url,body:JSON.parse(opts.body)});return {ok:true,json:async()=>opts && opts.body ? {ok:true} : {connected:false,authenticated:false,connection:{phase:'disabled',last_error:null}}};};
 await F.request('stop');
 assert.deepEqual(calls[1].body,{enabled:false});
 assert.ok(calls[1].url.includes('device=other'));
 assert.equal(S.get('other').communicationError,false);
 assert.equal(S.get('other').connection.phase,'disabled');
 let statusRelease;
 sandbox.fetch=(url,opts)=>opts && opts.body ? Promise.resolve({ok:true,json:async()=>({ok:true})}) : new Promise(r=>statusRelease=r);
 const stale=F.request('connect');
 await new Promise(r=>setImmediate(r));
 S.dispatch({type:'status',device:'other',connected:true,authenticated:true,connection:{phase:'connected',last_error:null}});
 statusRelease({ok:true,json:async()=>({connected:false,authenticated:false,connection:{phase:'disabled',last_error:null}})});
 await stale;
 assert.equal(S.get('other').connection.phase,'connected','new SSE must supersede older fetched snapshot');
 let rejectPost;
 sandbox.fetch=()=>new Promise((resolve,reject)=>rejectPost=reject);
 const oldPost=F.request('stop');
 S.dispatch({type:'status',device:'other',connected:true,authenticated:true,connection:{phase:'connected',last_error:null}});
 rejectPost(new Error('old POST failed')); await oldPost;
 assert.equal(S.get('other').communicationError,false,'old POST failure must not override newer healthy SSE');
 let rejectGet;
 sandbox.fetch=(url,opts)=>opts && opts.body ? Promise.resolve({ok:true,json:async()=>({ok:true})}) : new Promise((resolve,reject)=>rejectGet=reject);
 const oldGet=F.request('stop');
 await new Promise(r=>setImmediate(r));
 S.dispatch({type:'status',device:'other',connected:true,authenticated:true,connection:{phase:'connected',last_error:null}});
 rejectGet(new Error('old GET failed')); await oldGet;
 assert.equal(S.get('other').communicationError,false,'old GET failure must not override newer healthy SSE');
 assert.equal(F.communicationFailed('other', (S.get('other').feedbackRevision || 0)-1), false);
 assert.equal(S.get('other').communicationError,false);
 for (const page of ['app.js','phone.js']) {
  const pageSource=fs.readFileSync(path.join(root,page),'utf8');
  assert.equal((pageSource.match(/communicationFailed\(wanted, feedbackRevision\)/g)||[]).length,2,page+' initial and polling failure use revision guard');
 }
 S.setStreamUnavailable(true);
 assert.equal(S.get('default').communicationError,true);
 assert.equal(S.get('other').communicationError,true);
 assert.equal(S.get('new-device').communicationError,true);
 S.setStreamUnavailable(false);
 S.dispatch({type:'status',device:'other',connected:true,authenticated:true});
 assert.equal(S.get('other').communicationError,false);
 let timeout;
 sandbox.setTimeout=fn=>{timeout=fn;return 1;}; sandbox.clearTimeout=()=>{};
 sandbox.fetch=()=>new Promise(()=>{});
 const hanging=F.request('stop');
 await new Promise(r=>setImmediate(r));
 timeout(); await hanging;
 assert.equal(S.get('other').connectionRequest,false);
 assert.equal(S.get('other').communicationError,true);
 console.log('connection feedback tests passed');
})().catch(e=>{console.error(e);process.exitCode=1;});
